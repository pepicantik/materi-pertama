//operasi aritmatika

// a + 1; //ekspresi
// a = a + 1; //statement

// % <- modulo
// ++ <- increment
// -- <- decrement
// ** <- pangkat atau power

let x = 10;
console.log(x + 1);
console.log(x - 1);
console.log(x / 1);
console.log(x * 1); 

//aritmatika khusu di js
console.log(x % 4); //hasil sisa pembagian
console.log(x ** 2); 

//pemograman biasa
x = x +1;
console.log(x);
x++; //fungsinya dia akan menambahkan 1, lebih singkat dari x = x + 1
console.log(x);
x--; //ini sama cuma versi pengurangan
console.log(x);

